import pytest

from allowlist import ALLOWLIST, PLATFORM_SUFFIXES, is_allowlisted, is_never_block, is_platform

TEST_ALLOWLIST = frozenset({'wikipedia.org', 'bbc.co.uk', 'google.com', 'github.com', 'example.com'})


@pytest.mark.parametrize('url', [
    'https://www.wikipedia.org/',
    'https://en.wikipedia.org/wiki/Phishing',     # subdomain of an allowlisted domain
    'https://www.bbc.co.uk/news/technology',
    'github.com/scikit-learn/scikit-learn',
    'HTTPS://WWW.GOOGLE.COM/search?q=a',
])
def test_allowlisted(url):
    assert is_allowlisted(url, TEST_ALLOWLIST)


@pytest.mark.parametrize('url', [
    'https://wikipedia.org.evil.xyz/login',        # allowlisted name as a prefix, not the domain
    'https://evilwikipedia.org/',                  # suffix match must stop at a dot
    'https://unknown-site.net/',
    'https://co.uk/',                              # never match a bare public suffix
    'https://sites.google.com/view/phish',         # user content on an allowlisted domain
    'https://docs.google.com/forms/d/e/x/viewform',
    'https://someone.github.io/page',
    '',
    'http://[bad/',
])
def test_not_allowlisted(url):
    assert not is_allowlisted(url, TEST_ALLOWLIST)


@pytest.mark.parametrize('host', [
    'blogspot.com', 'my.blogspot.com', 'pages.dev', 'x.vercel.app', 'bit.ly',
    # Wildcard / dynamic DNS: anyone can mint any hostname under these
    'nip.io', 'paypal.com.127.0.0.1.nip.io', 'x.ddns.net', 'no-ip.com',
])
def test_platforms_are_excluded(host):
    assert is_platform(host)


def test_platform_match_is_suffix_on_dot_boundary():
    assert not is_platform('notblogspot.com')
    assert not is_platform('wikipedia.org')


def test_shipped_allowlist_contains_no_platforms():
    # allowlist.txt is generated by the notebook; a platform slipping in would be a bypass
    assert not [d for d in ALLOWLIST if is_platform(d)]


def test_platform_list_has_no_duplicates():
    assert len(PLATFORM_SUFFIXES) == len(set(PLATFORM_SUFFIXES))


@pytest.mark.parametrize('url', [
    'https://docs.google.com/forms/d/e/1FAIpQLSf3kD8x/viewform',
    'https://docs.google.com/document/d/abc/edit',
    'https://drive.google.com/file/d/abc/view',
    'https://forms.gle/AbC123',
    'https://myteam.sharepoint.com/sites/Eng/Shared%20Documents/x.docx',
    'https://contoso-my.sharepoint.com/personal/x',
    'https://onedrive.live.com/?id=ABC123',
    'https://1drv.ms/u/s!abc',
])
def test_never_block_document_platforms(url):
    assert is_never_block(url)


@pytest.mark.parametrize('url', [
    # Look-alikes of the platforms must still be scored
    'http://docs.google.com.account-verify.xyz/forms/login',
    'https://evil-sharepoint.com/login',
    'https://sharepoint.com.evil.top/',
    'https://google.com/',
    'https://sites.google.com/view/x',
    '',
])
def test_never_block_rejects_lookalikes(url):
    assert not is_never_block(url)
